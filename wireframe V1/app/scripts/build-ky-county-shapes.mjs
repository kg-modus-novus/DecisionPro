// Generates src/data/alp/kyCountyShapes.js: SVG path data for Kentucky's 120
// counties, keyed by 5-digit FIPS, from the us-atlas county TopoJSON (US Census
// Bureau cartographic boundary files, 1:10,000,000). Run:
//   node scripts/build-ky-county-shapes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const atlasPath = require.resolve('us-atlas/counties-10m.json');
const atlasVersion = JSON.parse(readFileSync(require.resolve('us-atlas/package.json'), 'utf8')).version;
const topology = JSON.parse(readFileSync(atlasPath, 'utf8'));

const KY_STATE_FIPS = '21';
const VIEW_WIDTH = 1000;
const PADDING = 8;

const counties = feature(topology, topology.objects.counties).features
  .filter((f) => String(f.id).padStart(5, '0').startsWith(KY_STATE_FIPS));

if (counties.length !== 120) {
  throw new Error(`Expected 120 Kentucky counties, found ${counties.length}`);
}

function ringsOf(geometry) {
  if (geometry.type === 'Polygon') return geometry.coordinates;
  if (geometry.type === 'MultiPolygon') return geometry.coordinates.flat();
  throw new Error(`Unsupported geometry ${geometry.type}`);
}

// Equirectangular projection with longitude scaled by cos(mid-latitude):
// adequate for a single state and keeps the script dependency-free.
let minLon = Infinity; let maxLon = -Infinity; let minLat = Infinity; let maxLat = -Infinity;
for (const county of counties) {
  for (const ring of ringsOf(county.geometry)) {
    for (const [lon, lat] of ring) {
      minLon = Math.min(minLon, lon); maxLon = Math.max(maxLon, lon);
      minLat = Math.min(minLat, lat); maxLat = Math.max(maxLat, lat);
    }
  }
}
const kx = Math.cos(((minLat + maxLat) / 2) * (Math.PI / 180));
const scale = (VIEW_WIDTH - 2 * PADDING) / ((maxLon - minLon) * kx);
const viewHeight = Math.ceil((maxLat - minLat) * scale + 2 * PADDING);
const project = ([lon, lat]) => [
  +(PADDING + (lon - minLon) * kx * scale).toFixed(1),
  +(PADDING + (maxLat - lat) * scale).toFixed(1),
];

const shapes = counties
  .map((county) => {
    const fips = String(county.id).padStart(5, '0');
    let sx = 0; let sy = 0; let n = 0;
    const d = ringsOf(county.geometry)
      .map((ring) => ring.map((pt, i) => {
        const [x, y] = project(pt);
        sx += x; sy += y; n += 1;
        return `${i === 0 ? 'M' : 'L'}${x} ${y}`;
      }).join('') + 'Z')
      .join('');
    return { fips, name: county.properties.name, d, cx: +(sx / n).toFixed(1), cy: +(sy / n).toFixed(1) };
  })
  .sort((a, b) => a.fips.localeCompare(b.fips));

const out = `/**
 * Generated by scripts/build-ky-county-shapes.mjs — do not hand-edit.
 * Kentucky county outlines from us-atlas ${atlasVersion} (US Census Bureau
 * cartographic boundary files, 1:10,000,000), projected to SVG coordinates.
 * Geometry only: no Medicaid or population figures live here.
 */
export const KY_COUNTY_SHAPES = ${JSON.stringify({
  source: `us-atlas@${atlasVersion} counties-10m.json (US Census Bureau cartographic boundaries)`,
  viewBox: `0 0 ${VIEW_WIDTH} ${viewHeight}`,
  counties: shapes,
}, null, 1)};
`;

const target = fileURLToPath(new URL('../src/data/alp/kyCountyShapes.js', import.meta.url));
writeFileSync(target, out);
console.log(`Wrote ${shapes.length} counties, viewBox 0 0 ${VIEW_WIDTH} ${viewHeight}, ${(out.length / 1024).toFixed(0)} KB`);
